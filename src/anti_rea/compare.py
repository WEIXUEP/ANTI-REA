"""Reproducible build/run/audit matrix with explicit unavailable configurations."""
import argparse
from collections import Counter
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import platform
import statistics
import subprocess
import sys
import time
from .launcher import doctor, version

PRESETS = ["baseline", "stripped", "protected", "obfuscated-light", "obfuscated-medium", "obfuscated-heavy", "mixed-vm"]
LEVELS = dict(zip(PRESETS, ["NONE", "NONE", "NONE", "LIGHT", "MEDIUM", "HEAVY", "MIXED_VM"]))
DENIED = ["Invalid mesh topology", "Internal spectral preconditioner stalled", "Internal constitutive tensor inversion failed",
          "Internal basis ordering invariant failed", "ResonantKernel", "print_rtti", "internal_preconditioner_budget",
          "proprietary_basis_weights.dat", "main.cpp", "engine.cpp", "policy.cpp", "diagnostics.cpp"]


def summary(values):
    return dict(median=statistics.median(values), minimum=min(values), maximum=max(values),
                stdev=statistics.pstdev(values), samples=len(values))


def expected(seed, rounds):
    value = seed
    for _ in range(rounds):
        branch = value & 3
        if branch == 0:
            value = (value * 17) ^ 0xa341316c
        elif branch == 1:
            value = (value + 0xc8013ea4) ^ (value >> 3)
        elif branch == 2:
            value = (value ^ 0xad90777d) + (value << 5)
        else:
            value = value * 31 + 0x7e95761e
        value &= 0xffffffff
        value = (((value ^ 0x5a827999) * 33) + (value >> 7)) & 0xffffffff
    return value


def measure(executable, mode, samples):
    wall, kernel, checksums = [], [], set()
    for _ in range(samples):
        start = time.perf_counter()
        result = subprocess.run([str(executable), mode, "123"], check=True, capture_output=True, text=True, timeout=30)
        wall.append(time.perf_counter() - start)
        checksum, duration = result.stdout.split()
        checksums.add(int(checksum))
        kernel.append(float(duration))
    if checksums != {expected(123, 1 if mode == "startup" else 500000)}:
        raise ValueError("Numerical checksum mismatch")
    return dict(process_wall_seconds=summary(wall), inner_seconds=summary(kernel), checksum=checksums.pop())


def render(report):
    lines = ["# Measured Comparison", "", "Generated by `tools/anti_rea.py compare`; no simulated measurements.", "",
             "## Environment", "", f"- Platform: {report['platform']}", f"- Compiler: {report['compiler']}",
             f"- Build jobs: {report['jobs']}; samples per workload: {report['samples']}.",
             "- RelWithDebInfo, the same compiler and O2 optimization for all completed configurations.",
             "- Build time is one clean compile/link observation, excluding configure, tests and installation.",
             "- Sizes include the executable and the example shared library, not system dependencies.", "",
             "## Results", "", "| Configuration | Status | Build (s) | Bytes | Bench median (ms) | Startup median (ms) | Denied matches |",
             "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for row in report["configurations"]:
        if row["status"] == "Passed":
            lines.append(f"| {row['preset']} | Passed | {row['build_seconds']:.3f} | {row['bytes']} | "
                         f"{row['bench']['inner_seconds']['median']*1000:.3f} | "
                         f"{row['startup']['process_wall_seconds']['median']*1000:.3f} | {row['denied_matches']} |")
        else:
            lines.append(f"| {row['preset']} | {row['status']} | - | - | - | - | - |")
    lines.extend(["", "## Evidence and Limits", ""])
    for row in report["configurations"]:
        lines.append(f"- **{row['preset']}**: " + row.get("reason", f"tests passed; audit categories: {row.get('categories', {})}"))
    lines.extend(["", "Only `denied_matches` is the example's sensitive-text gate; other findings require review.",
                  "Private build files can contain original identifiers. The installed release is a separate artifact.",
                  "A smaller file or fewer strings does not quantify resistance to a skilled reverse engineer.",
                  "Randomized sealed ciphertext makes binary hashes vary across fresh configurations.",
                  "Windows execution and xollvm configurations without an available toolchain are not claimed as tested.", ""])
    return "\n".join(lines)


def compare(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", required=True)
    parser.add_argument("--opt", default="")
    parser.add_argument("--plugin", default="")
    parser.add_argument("--presets", nargs="+", choices=PRESETS, default=PRESETS)
    parser.add_argument("--jobs", type=int, default=8)
    parser.add_argument("--samples", type=int, default=9)
    parser.add_argument("--out", default="build/comparison")
    parser.add_argument("--publish", help="Optional public summary prefix; excludes raw audit findings")
    args = parser.parse_args(argv)
    if args.samples < 3 or args.jobs < 1:
        parser.error("Use at least three samples and one build job")
    root = Path(__file__).resolve().parents[2]
    # clang++ can be a symlink to clang; resolving it changes the linker's driver mode.
    compiler = Path(os.path.abspath(args.compiler))
    opt = Path(args.opt).resolve() if args.opt else compiler.parent / ("opt.exe" if os.name == "nt" else "opt")
    spec = importlib.util.spec_from_file_location("anti_rea_audit", root / "skills/cpp-leakage-audit/scripts/audit.py")
    audit = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(audit)
    report = dict(schema=1, platform=platform.system() + " " + platform.machine(),
                  compiler=version(compiler)[1], jobs=args.jobs, samples=args.samples, configurations=[])
    prefix = Path(args.out).resolve()
    prefix.parent.mkdir(parents=True, exist_ok=True)
    failures = False
    for preset in args.presets:
        level = LEVELS[preset]
        row = dict(preset=preset)
        report["configurations"].append(row)
        if level != "NONE":
            try:
                row["toolchain"] = doctor(compiler, opt, level, args.plugin)
            except (ValueError, OSError, subprocess.CalledProcessError) as error:
                row.update(status="Not run", reason=str(error).replace(str(root), "<PROJECT>"))
                continue
        toolchain_id = hashlib.sha256(str(compiler).encode()).hexdigest()[:12]
        build = root / "build" / ("matrix-" + toolchain_id) / preset
        install = root / "out" / ("matrix-" + toolchain_id) / preset
        row["build_directory"] = build.relative_to(root).as_posix()
        row["release_directory"] = install.relative_to(root).as_posix()
        log = prefix.parent / (prefix.name + "-" + preset + ".log")
        try:
            with log.open("w") as stream:
                def run(command):
                    subprocess.run([str(arg) for arg in command], cwd=root, check=True, stdout=stream,
                                   stderr=subprocess.STDOUT, timeout=180)
                configure = ["cmake", "--preset", preset, "-B", build,
                             "-DCMAKE_CXX_COMPILER=" + str(compiler),
                             "-DCMAKE_INSTALL_PREFIX=" + str(install),
                             "-DPython3_EXECUTABLE=" + sys.executable]
                if preset not in {"baseline", "stripped"}:
                    configure.extend(["-DANTI_REA_OPT=" + str(opt), "-DANTI_REA_XOLLVM_PLUGIN=" + args.plugin])
                if os.name == "nt":
                    configure.extend(["-G", "NMake Makefiles JOM"])
                run(configure)
                start = time.perf_counter()
                run(["cmake", "--build", build, "--clean-first", "-j", args.jobs])
                row["build_seconds"] = time.perf_counter() - start
                run(["ctest", "--test-dir", build, "--output-on-failure"])
                run(["cmake", "--install", build, "--prefix", install])
            executable = install / "bin" / ("anti-rea-demo.exe" if os.name == "nt" else "anti-rea-demo")
            row["startup"] = measure(executable, "startup", args.samples)
            row["bench"] = measure(executable, "bench", args.samples)
            artifacts = [path for path in executable.parent.iterdir()
                         if path == executable or path.suffix.lower() in {".dll", ".so"}]
            row["bytes"] = sum(path.stat().st_size for path in artifacts)
            row["sha256"] = {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in artifacts}
            findings, unchecked = [], []
            for artifact in artifacts:
                items, skipped = audit.scan_binary(artifact, deny=DENIED)
                findings.extend(items)
                unchecked.extend(skipped)
            row["denied_matches"] = sum(item["category"] == "denied-text" for item in findings)
            row["categories"] = dict(Counter(item["category"] for item in findings))
            row["not_checked"] = unchecked
            row["audit"] = dict(findings=findings, not_checked=unchecked)
            row["ordinary_string_present"] = any(b"Internal dispatch schedule uses a calibrated branch table" in path.read_bytes()
                                                 for path in artifacts)
            if level != "NONE" and row["ordinary_string_present"]:
                raise ValueError("xollvm ordinary-string protection did not survive code generation")
            if preset not in {"baseline", "stripped"}:
                if any(str(root).encode() in path.read_bytes() for path in artifacts):
                    raise ValueError("Developer source/build root in the installed release")
            row["applied_passes"] = [dict(source=value["source"], verified=value["verified_passes"])
                                    for path in (build / "private/maps").glob("*.json")
                                    if "verified_passes" in (value := json.loads(path.read_text()))]
            forbidden = [path for path in install.rglob("*") if path.is_file() and
                         (path.suffix.lower() in {".json", ".ll", ".pdb", ".hex", ".obj", ".o"} or "private" in path.parts)]
            if forbidden:
                raise ValueError("Private development artifacts in the install tree")
            if preset not in {"baseline", "stripped"} and row["denied_matches"]:
                raise ValueError("Sensitive-text release gate failed")
            row["status"] = "Passed"
        except (ValueError, OSError, subprocess.SubprocessError) as error:
            row.update(status="Failed", reason=str(error).replace(str(root), "<PROJECT>"))
            failures = True
        print(preset + ": " + row["status"], flush=True)
    # Publishable reports redact developer roots from evidence; raw logs stay under build/.
    text = json.dumps(report, indent=2).replace(str(root), "<PROJECT>")
    text = text.replace(str(compiler.parent.parent.parent.parent), "<TOOLCHAIN>")
    sanitized = json.loads(text)
    prefix.with_suffix(".json").write_text(json.dumps(sanitized, indent=2) + "\n")
    prefix.with_suffix(".md").write_text(render(sanitized))
    if args.publish:
        public = {**sanitized, "configurations": [{key: value for key, value in row.items() if key != "audit"}
                                                 for row in sanitized["configurations"]]}
        destination = Path(args.publish)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.with_suffix(".json").write_text(json.dumps(public, indent=2) + "\n")
        destination.with_suffix(".md").write_text(render(public))
    print("Reports: " + str(prefix.with_suffix(".md")))
    return int(failures)

"""Convenient three-release measurement and evidence-backed difference reports."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from .compare import compare
from .launcher import doctor

PROFILES = ("baseline", "stripped", "protected")
METRICS = (
    ("bytes", "Release size", "bytes"),
    ("build_seconds", "Clean build", "s"),
    ("startup", "Startup wall median", "ms"),
    ("bench", "Benchmark inner median", "ms"),
    ("denied_matches", "Sensitive corpus matches", "matches"),
)


def executable(value):
    """Keep the clang++ driver basename even when it is a symlink to clang."""
    found = shutil.which(str(value))
    if not found:
        raise ValueError("Executable not found: " + str(value))
    return Path(os.path.abspath(found))


def toolchain(root, compiler=None, opt=None):
    if compiler:
        chosen = executable(compiler)
        optimizer = executable(opt) if opt else chosen.parent / ("opt.exe" if os.name == "nt" else "opt")
        doctor(chosen, optimizer)
        return chosen, optimizer
    candidates = [root / "build/toolchains/xollvm23/bin/clang++"]
    candidates.extend(name for name in ("clang++", "clang++-23", "clang++-22", "clang++-18")
                      if shutil.which(name))
    reasons = []
    for candidate in candidates:
        if not shutil.which(str(candidate)):
            continue
        chosen = executable(candidate)
        optimizer = executable(opt) if opt else chosen.parent / ("opt.exe" if os.name == "nt" else "opt")
        if not opt and not optimizer.is_file() and chosen.name.startswith("clang++-"):
            versioned = shutil.which("opt-" + chosen.name.split("-", 1)[1])
            if versioned:
                optimizer = Path(os.path.abspath(versioned))
        try:
            doctor(chosen, optimizer)
            return chosen, optimizer
        except (ValueError, OSError, subprocess.SubprocessError) as error:
            reasons.append(str(error))
    raise ValueError("No compatible Clang/opt pair found. Set --compiler and --opt. " + "; ".join(reasons))


def metric(row, key):
    if key == "startup":
        return row[key]["process_wall_seconds"]["median"] * 1000
    if key == "bench":
        return row[key]["inner_seconds"]["median"] * 1000
    return row[key]


def differences(report):
    if report.get("schema") != 1 or not isinstance(report.get("configurations"), list):
        raise ValueError("Unsupported measurement report; expected comparison schema 1")
    rows = {}
    for row in report["configurations"]:
        if row["preset"] in PROFILES:
            if row["preset"] in rows:
                raise ValueError("Duplicate configuration: " + row["preset"])
            rows[row["preset"]] = row
    statuses = {name: rows.get(name, {}).get("status", "Missing") for name in PROFILES}
    complete = all(status == "Passed" for status in statuses.values())
    result = dict(schema=1, complete=complete, statuses=statuses, comparisons=[])
    if not complete:
        return result
    for reference, target in (("baseline", "stripped"), ("baseline", "protected"), ("stripped", "protected")):
        metrics = []
        for key, label, unit in METRICS:
            before, after = metric(rows[reference], key), metric(rows[target], key)
            metrics.append(dict(metric=key, label=label, unit=unit, reference=before, target=after,
                                delta=after - before,
                                percent=(after - before) / before * 100 if before else None))
        result["comparisons"].append(dict(reference=reference, target=target, metrics=metrics))
    return result


def render_differences(result):
    lines = ["# Three-Release Differences", "",
             "Generated by `tools/measure.py`. Delta = target - reference; a negative value means a reduction.", ""]
    for name, status in result["statuses"].items():
        lines.append(f"- {name}: {status}")
    if not result["complete"]:
        lines.extend(["", "Comparison incomplete. No deltas are reported; inspect the full report and build logs.", ""])
        return "\n".join(lines)
    for pair in result["comparisons"]:
        lines.extend(["", f"## {pair['target']} vs {pair['reference']}", "",
                      "| Metric | Reference | Target | Delta | Change |",
                      "| --- | ---: | ---: | ---: | ---: |"])
        for entry in pair["metrics"]:
            percent = "N/A (zero reference)" if entry["percent"] is None else f"{entry['percent']:+.2f}%"
            digits = 0 if entry["unit"] in {"bytes", "matches"} else 3
            lines.append(f"| {entry['label']} ({entry['unit']}) | {entry['reference']:.{digits}f} | "
                         f"{entry['target']:.{digits}f} | {entry['delta']:+.{digits}f} | {percent} |")
    lines.extend(["", "## Interpretation", "",
                  "Build duration is one clean compile/link observation, not a repeated-build statistic.",
                  "Runtime medians are noisy, especially process startup; inspect sample ranges and standard deviations in the full JSON.",
                  "Sensitive corpus matches count scanner findings, not unique secrets or all possible leaks.",
                  "A zero corpus count does not prove that no paths, symbols or other readable strings remain.",
                  "The protected profile includes release stripping; protected vs stripped isolates the additional protection package, not each individual mechanism.",
                  "These differences do not measure resistance to a skilled reverse engineer.", ""])
    return "\n".join(lines)


def main(argv=None):
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", help="Clang C++ driver; auto-detected when omitted")
    parser.add_argument("--opt", help="Matching LLVM opt; inferred when omitted")
    parser.add_argument("--jobs", type=int, default=8)
    parser.add_argument("--samples", type=int, default=9)
    parser.add_argument("--out", default="build/measurement", help="Report prefix, relative to the project root")
    parser.add_argument("--report-only", type=Path, help="Read an existing comparison JSON without building")
    args = parser.parse_args(argv)
    if args.jobs < 1 or args.samples < 3:
        parser.error("Use at least one build job and three samples")
    prefix = Path(args.out)
    if not prefix.is_absolute():
        prefix = root / prefix
    prefix = prefix.resolve()
    try:
        code = 0
        source = args.report_only
        if source is None:
            compiler, opt = toolchain(root, args.compiler, args.opt)
            print("Compiler: " + str(compiler), flush=True)
            code = compare(["--compiler", str(compiler), "--opt", str(opt),
                            "--presets", *PROFILES, "--jobs", str(args.jobs),
                            "--samples", str(args.samples), "--out", str(prefix)])
            source = prefix.with_suffix(".json")
        result = differences(json.loads(source.read_text(encoding="utf-8")))
        result["source_report"] = os.path.relpath(source.resolve(), prefix.parent)
        prefix.parent.mkdir(parents=True, exist_ok=True)
        destination = prefix.with_name(prefix.name + "-differences")
        destination.with_suffix(".json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        text = render_differences(result)
        destination.with_suffix(".md").write_text(text, encoding="utf-8")
        print(text)
        print("Difference report: " + str(destination.with_suffix(".md")))
        return code or int(not result["complete"])
    except (ValueError, OSError, KeyError, TypeError, subprocess.SubprocessError) as error:
        print("Measurement failed: " + str(error), file=sys.stderr)
        return 1
